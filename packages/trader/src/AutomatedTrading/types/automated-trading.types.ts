/**
 * Exact snapshot of the manual trading form.
 */
export type ManualTradeSelection = {
    symbol: string;
    currency: string;
    amount: number;
    basis: 'stake' | 'payout';

    contractType: string;
    tradeType: string;

    proposalKey: string;
    proposalId?: string;

    /**
     * Exact proposal request generated by the manual trading UI.
     */
    proposalRequest: Record<string, unknown>;
};

export type ManualTradingMethod =
    | 'FIXED'
    | 'MARTINGALE'
    | 'STAKE_LIST';

export type ManualExecutionSpeed =
    | 'NORMAL'
    | 'FAST'
    | 'ULTRA';

export type ManualAutomationConfig = {
    /**
     * Exact manual trade that will be repeated.
     */
    selection: ManualTradeSelection;

    /**
     * Session cumulative profit at which automation stops.
     *
     * Example:
     * 10 = stop after cumulative session profit reaches 10.
     */
    takeProfit?: number;

    /**
     * Session cumulative loss at which automation stops.
     *
     * Example:
     * 100 = stop after cumulative session loss reaches -100.
     */
    stopLoss?: number;

    /**
     * Continue placing the same trade after settlement.
     */
    repeat: boolean;

    /**
     * Maximum number of completed trades.
     */
    maxTrades?: number;

    /**
     * Delay between completed trade and next trade.
     */
    cooldownMs?: number;

    /**
     * Risk-management method.
     */
    tradingMethod?: ManualTradingMethod;

    /**
     * Martingale multiplier.
     *
     * Example:
     * 3 => 1 -> 3 -> 9 -> 27
     */
    martingaleMultiplier?: number;

    /**
     * Number of consecutive losses before martingale starts.
     *
     * Example:
     * 1 = start martingale after first loss.
     */
    startMartingaleAfter?: number;

    /**
     * Maximum martingale level.
     */
    maxMartingaleLevel?: number;

    /**
     * Stop automation when maximum martingale level is reached.
     */
    stopAfterMaxMartingale?: boolean;

    /**
     * Manual stake sequence.
     *
     * Example:
     * [1, 2, 5, 10]
     */
    stakeList?: number[];

    /**
     * Stop when the stake list reaches its end.
     */
    stopAfterStakeList?: boolean;

    /**
     * DT Nexus-style "Trade Differs".
     *
     * When enabled, DIGITDIFF is used first and the
     * selected manual contract is used after a loss.
     */
    tradeDiffers?: boolean;

    /**
     * Execution speed.
     */
    executionSpeed?: ManualExecutionSpeed;

    /**
     * Backwards compatibility with the previous implementation.
     */
    stopOnProfit?: number;
    stopOnLoss?: number;
};

